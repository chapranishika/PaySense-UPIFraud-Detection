"""
================================================================================
  PaySense — OOD Generalization Remediation Experiment
  ────────────────────────────────────────────────────────────────────────────
  Question: SYNTHETIC_GROUNDING.md found the frozen model ranks WORSE
  (ROC-AUC ~0.70) on a full-40-feature synthetic dataset generated by a
  genuinely different process than it does on GENERALIZATION_CHECK.md's
  Dataset 1, which supplies only 6/40 features but is drawn from a real UPI
  transaction stream (ROC-AUC ~0.79 ensemble). Feature completeness cannot
  explain that gap; SYNTHETIC_GROUNDING.md's own conclusion is that the model
  has partially overfit to paysense_pipeline.py's specific anchor/supplement
  correlation structure -- not just to which fields happen to be populated.

  This script tests one falsifiable remediation: does training on a BLEND of
  the original pipeline's data plus a differently-structured generative
  process reduce that overfitting, measured on data never used in training?
  A second, cheaper control (heavier regularization on the ORIGINAL data
  only) tests whether this is a regularization problem rather than (or in
  addition to) a data-diversity problem.

  LEAKAGE DISCIPLINE (the main risk in this experiment)
  ────────────────────────────────────────────────────────────────────────────
  generate_grounded_synthetic_dataset.py's on-disk synthetic_grounded_dataset
  .csv (SEED=918273, 25,000 rows) was generated for SYNTHETIC_GROUNDING.md
  and has never been trained on by anything. This script:
    1. Generates a SECOND, independently-seeded synthetic dataset
       (SEED=445566, 12,000 rows) via the *same* generator function --
       different seed, same generative structure/weights as the 918273 set,
       but a disjoint random draw -- and blends ONLY this one into training
       (Variant A).
    2. Keeps the EXISTING seed-918273 dataset entirely unseen by training and
       uses it as the held-out synthetic evaluation set for all three models
       (baseline, A, B). Its baseline ensemble numbers are cited verbatim
       from SYNTHETIC_GROUNDING.md (already computed against that exact file
       by generalization_check_synthetic.py) rather than re-run.
    3. Never touches paysense_master_dataset.csv's TEST partition (the
       canonical 20% / 6,000-row split) with anything from either synthetic
       dataset -- both the blend and the held-out set are entirely separate
       from that split, and the test partition itself is reproduced with the
       exact random_state=42 stratified split paysense_phase3.py uses.
    4. The two real external datasets (GENERALIZATION_CHECK.md Datasets 1 and
       3) are never trained on by anything in this project -- they don't even
       carry the full 40-feature schema, so training on them isn't possible,
       let alone tempting.

  A regression test (tests/test_ood_generalization_remediation.py) locks in
  that the blend seed (445566) and the held-out eval seed (918273) are
  verifiably different, and that no row from the held-out CSV appears in the
  blend CSV (by transaction_id, which is seed-namespaced: SGT0000000 vs a
  disjoint id space per seed).

  NO CHANGES to artefacts/paysense_model.pkl, paysense_preprocessor.pkl, or
  paysense_threshold.pkl happen anywhere in this script. All new artifacts
  are saved under new filenames and are not wired into src/fraud_model.py or
  main.py -- to score them through the real ensemble path this script
  monkeypatches the in-memory fraud_model._state object only (never touches
  the module's file-path constants or any file on disk).

  Outputs:
    - synthetic_grounded_dataset_seed445566_blend.csv   (blend-only data)
    - artefacts/paysense_model_blended_training.pkl        (Variant A model)
    - artefacts/paysense_preprocessor_blended_training.pkl (Variant A preprocessor)
    - artefacts/paysense_model_regularized.pkl              (Variant B model)
    - ood_generalization_remediation_results.json          (all numbers)

  Run
  ───
      venv\\Scripts\\python.exe ood_generalization_remediation.py
================================================================================
"""

