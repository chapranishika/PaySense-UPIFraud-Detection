def build_preprocessor(cat_cols, num_cols):
    cat_pipeline = Pipeline([
        ("impute", SimpleImputer(strategy="most_frequent")),
        ("encode", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1,
                                   encoded_missing_value=-2)),
    ])
    num_pipeline = Pipeline([("impute", SimpleImputer(strategy="median"))])
    return ColumnTransformer(
        transformers=[("cat", cat_pipeline, cat_cols), ("num", num_pipeline, num_cols)],
        remainder="drop", verbose_feature_names_out=False,
    )


def monotone_tuple(feature_names):
    return tuple(1 if f in BEHAVIORAL_FEATURES else 0 for f in feature_names)


def sweep_thresholds(y_test, y_proba, thresholds=np.arange(0.05, 0.51, 0.05)):
    rows = []
    for t in thresholds:
        y_pred_t = (y_proba >= t).astype(int)
        cm = confusion_matrix(y_test, y_pred_t)
        tn, fp, fn, tp = cm.ravel()
        rows.append({
            "threshold": round(float(t), 2),
            "precision": float(precision_score(y_test, y_pred_t, zero_division=0)),
            "recall": float(recall_score(y_test, y_pred_t, zero_division=0)),
            "f1": float(f1_score(y_test, y_pred_t, zero_division=0)),
            "tp": int(tp), "fp": int(fp), "fn": int(fn), "tn": int(tn),
        })
    return rows


def score_ensemble_dataframe(records, threshold_override=None):
    """Scores a list-of-dicts through fraud_model.score() using whatever is
    CURRENTLY monkeypatched into fraud_model._state (see swap_ps_state below).
    threshold_override lets us force every model to be judged at the SAME
    deployed threshold (0.30) rather than each variant's own state threshold."""
    n = len(records)
    ensemble_scores = np.empty(n, dtype=float)
    paysense_scores = np.full(n, np.nan, dtype=float)
    lr_scores = np.full(n, np.nan, dtype=float)
    rules_scores = np.empty(n, dtype=float)
    t0 = time.time()
    for i, rec in enumerate(records):
        clean = {k: (None if isinstance(v, float) and np.isnan(v) else v) for k, v in rec.items()}
        result = fraud_model.score(clean)
        ensemble_scores[i] = result.ensemble_score
        if result.paysense_score is not None:
            paysense_scores[i] = result.paysense_score
        if result.light_lr_score is not None:
            lr_scores[i] = result.light_lr_score
        rules_scores[i] = result.rules_score
        if i and i % 10000 == 0:
            print(f"    ... {i:,} / {n:,} rows scored ({time.time()-t0:.1f}s elapsed)")
    elapsed = time.time() - t0
    print(f"    scored {n:,} rows in {elapsed:.1f}s ({n/max(elapsed,1e-9):.0f} rows/sec)")
    thr = threshold_override if threshold_override is not None else fraud_model.get_state().ps_threshold
    return {
        "ensemble_scores": ensemble_scores,
        "paysense_scores": paysense_scores,
        "lr_scores": lr_scores,
        "rules_scores": rules_scores,
        "threshold_used": thr,
    }


class swap_ps_state:
    """Context manager: temporarily monkeypatches the in-process
    fraud_model._state PaySense fields (model/preprocessor/features/threshold)
    to a candidate artifact, restoring the previous (frozen) state on exit.
    Never touches fraud_model.py's file-path constants or any file on disk --
    this is purely an in-memory swap for scoring purposes."""

    def __init__(self, model, prep, features, threshold=DEPLOYED_THRESHOLD):
        self.model, self.prep, self.features, self.threshold = model, prep, features, threshold
        self._saved = None

    def __enter__(self):
        st = fraud_model.get_state()
        self._saved = (st.ps_model, st.ps_prep, st.ps_features, st.ps_threshold)
        st.ps_model, st.ps_prep, st.ps_features, st.ps_threshold = (
            self.model, self.prep, self.features, self.threshold,
        )
        return st

    def __exit__(self, *exc):
        st = fraud_model.get_state()
        st.ps_model, st.ps_prep, st.ps_features, st.ps_threshold = self._saved
        return False


def metrics_from_scores(y, scores, threshold):
    preds = (scores >= threshold).astype(int)
    roc_auc = roc_auc_score(y, scores)
    pr_auc = average_precision_score(y, scores)
    cm = confusion_matrix(y, preds)
    tn, fp, fn, tp = cm.ravel() if cm.shape == (2, 2) else (None, None, None, None)
    return {
        "roc_auc": float(roc_auc), "pr_auc": float(pr_auc),
        "confusion_matrix": cm.tolist(),
        "tp": int(tp) if tp is not None else None, "fp": int(fp) if fp is not None else None,
        "fn": int(fn) if fn is not None else None, "tn": int(tn) if tn is not None else None,
        "recall": float(recall_score(y, preds, zero_division=0)),
        "precision": float(precision_score(y, preds, zero_division=0)),
        "max_score": float(np.nanmax(scores)),
        "n": int(len(y)), "n_fraud": int(np.sum(y)),
    }


def main():
    results = {}

    # ════════════════════════════════════════════════════════════════════
    #  STEP 0 — Reproduce paysense_phase3.py Block 0 split exactly
    # ════════════════════════════════════════════════════════════════════
    line("=")
    print("STEP 0 | Reproducing paysense_phase3.py Block 0 (split + preprocessing)")
    line("=")

    master_df = pd.read_csv(MASTER_CSV)
    master_df = master_df.drop(columns=DROP_COLS)
    X_master = master_df.drop(columns=[TARGET])
    y_master = master_df[TARGET].astype(int)

    X_train_raw, X_test_raw, y_train, y_test = train_test_split(
        X_master, y_master, test_size=0.20, random_state=RANDOM_STATE, stratify=y_master
    )
    assert int(y_test.sum()) == 253, f"Canonical test fraud count drifted: {int(y_test.sum())}"
    print(f"Canonical split confirmed: train={X_train_raw.shape}, test={X_test_raw.shape}, "
          f"fraud in test={int(y_test.sum())}/253")

    CAT_COLS = X_train_raw.select_dtypes(include=["object"]).columns.tolist()
    NUM_COLS = X_train_raw.select_dtypes(include=[np.number]).columns.tolist()
    FEATURE_NAMES = CAT_COLS + NUM_COLS

    # Baseline (frozen) artifacts -- loaded read-only, NEVER modified.
    frozen_model = joblib.load(os.path.join(ARTEFACTS_DIR, "paysense_model.pkl"))
    frozen_prep = joblib.load(os.path.join(ARTEFACTS_DIR, "paysense_preprocessor.pkl"))
    frozen_features = joblib.load(os.path.join(ARTEFACTS_DIR, "paysense_feature_names.pkl"))
    X_test_frozen_proc = frozen_prep.transform(X_test_raw)
    assert list(frozen_features) == FEATURE_NAMES, "Feature order mismatch vs frozen artifact."
    y_proba_baseline_test = frozen_model.predict_proba(X_test_frozen_proc)[:, 1]
    baseline_test_metrics = metrics_from_scores(y_test.values, y_proba_baseline_test, DEPLOYED_THRESHOLD)
    baseline_test_metrics["roc_auc_full"] = float(roc_auc_score(y_test, y_proba_baseline_test))
    print(f"Baseline (frozen model) canonical test @ tau={DEPLOYED_THRESHOLD}: "
          f"ROC-AUC={baseline_test_metrics['roc_auc']:.4f} "
          f"recall={baseline_test_metrics['recall']:.4f} "
          f"precision={baseline_test_metrics['precision']:.4f}")
    results["baseline_canonical_test"] = baseline_test_metrics
    results["baseline_canonical_test_sweep"] = sweep_thresholds(y_test, y_proba_baseline_test)

    # ════════════════════════════════════════════════════════════════════
    #  STEP 1 — Generate the independently-seeded BLEND synthetic dataset
    #  (SEED=445566, disjoint from the held-out SEED=918273 dataset already
    #  on disk). Same generator function/structure, different random draw.
    # ════════════════════════════════════════════════════════════════════
    line("=")
    print(f"STEP 1 | Generating blend synthetic dataset (seed={BLEND_SEED}, n={BLEND_N_TXN:,})")
    line("=")

    df_blend = gen_synth.generate(n_txn=BLEND_N_TXN, seed=BLEND_SEED, target_fraud_rate=0.04)
    df_blend.to_csv(BLEND_SYNTH_CSV, index=False)
    n_fraud_blend = int(df_blend["is_fraud"].sum())
    print(f"Blend dataset: {len(df_blend):,} rows, {n_fraud_blend:,} fraud "
          f"({n_fraud_blend/len(df_blend)*100:.2f}%) -- saved to {BLEND_SYNTH_CSV}")

    assert os.path.exists(HELD_OUT_SYNTH_CSV), (
        f"{HELD_OUT_SYNTH_CSV} (seed 918273) not found -- required as the held-out "
        f"synthetic evaluation set. Run generate_grounded_synthetic_dataset.py first."
    )
    df_held_out = pd.read_csv(HELD_OUT_SYNTH_CSV)
    # Disjointness check: transaction_id is NOT a valid signal here -- both
    # generator calls number rows sequentially from 0 regardless of seed
    # (transaction_id = f"SGT{idx:07d}" for idx in range(n_txn)), so the id
    # strings legitimately collide between the two files even though every
    # other column is an independent draw from a different seed. The real
    # leakage question is whether any FULL ROW (all generated content, not
    # just the arbitrary sequential id) is duplicated across the two files --
    # that would indicate the RNG streams weren't actually independent.
    compare_cols = [c for c in df_blend.columns if c != "transaction_id"]
    blend_rows = set(map(tuple, df_blend[compare_cols].astype(str).values.tolist()))
    held_out_rows = set(map(tuple, df_held_out[compare_cols].astype(str).values.tolist()))
    row_overlap = blend_rows & held_out_rows
    assert not row_overlap, (
        f"Blend (seed={BLEND_SEED}) and held-out (seed={HELD_OUT_SEED}) synthetic "
        f"sets share {len(row_overlap)} fully-identical rows -- the two seeds are "
        f"not actually producing independent draws."
    )
    print(f"Held-out synthetic set (seed={HELD_OUT_SEED}): {len(df_held_out):,} rows -- "
          f"confirmed 0 full-row duplicates with the blend set (seed={BLEND_SEED}); "
          f"transaction_id strings themselves DO collide by design (both generators "
          f"number rows sequentially from 0 regardless of seed) but that column is "
          f"dropped before training (DROP_COLS) and is not used as an identity key "
          f"anywhere in this script.")
    results["blend_dataset"] = {
        "seed": BLEND_SEED, "n_rows": len(df_blend), "n_fraud": n_fraud_blend,
        "fraud_rate": n_fraud_blend / len(df_blend),
    }
    results["held_out_synthetic_dataset"] = {
        "seed": HELD_OUT_SEED, "n_rows": len(df_held_out),
        "n_fraud": int(df_held_out["is_fraud"].sum()),
        "note": "Pre-existing file from SYNTHETIC_GROUNDING.md -- never trained on, here or before.",
    }

    # ════════════════════════════════════════════════════════════════════
    #  STEP 2 — Variant A: blended training data (original 80% train +
    #  blend synthetic), fresh preprocessor + model, monotone_constraints
    #  kept (matching the deployed model -- not regressing that fix).
    # ════════════════════════════════════════════════════════════════════
    line("=")
    print("STEP 2 | Variant A -- blended training data")
    line("=")

    X_blend = df_blend.drop(columns=DROP_COLS + [TARGET])
    y_blend = df_blend[TARGET].astype(int)
    # Column order must match X_train_raw exactly before concatenation.
    X_blend = X_blend[X_train_raw.columns]

    X_train_A_raw = pd.concat([X_train_raw, X_blend], ignore_index=True)
    y_train_A = pd.concat([y_train.reset_index(drop=True), y_blend.reset_index(drop=True)], ignore_index=True)
    print(f"Variant A training data: {len(X_train_raw):,} original + {len(X_blend):,} blend "
          f"= {len(X_train_A_raw):,} rows before SMOTE "
          f"({int(y_train_A.sum()):,} fraud, {y_train_A.mean()*100:.2f}%)")

    CAT_COLS_A = X_train_A_raw.select_dtypes(include=["object"]).columns.tolist()
    NUM_COLS_A = X_train_A_raw.select_dtypes(include=[np.number]).columns.tolist()
    FEATURE_NAMES_A = CAT_COLS_A + NUM_COLS_A
    assert set(FEATURE_NAMES_A) == set(FEATURE_NAMES), "Variant A feature set differs from baseline's 40."

    prep_A = build_preprocessor(CAT_COLS_A, NUM_COLS_A)
    prep_A.fit(X_train_A_raw)
    X_train_A_proc = prep_A.transform(X_train_A_raw)
    X_test_A_proc = prep_A.transform(X_test_raw)  # canonical test set, own preprocessor

    smote = SMOTE(sampling_strategy="auto", k_neighbors=5, random_state=RANDOM_STATE)
    X_train_A_bal, y_train_A_bal = smote.fit_resample(X_train_A_proc, y_train_A.values)
    print(f"After SMOTE: {X_train_A_bal.shape}")

    kwargs_A = dict(BASE_XGB_KWARGS)
    kwargs_A["monotone_constraints"] = monotone_tuple(FEATURE_NAMES_A)
    model_A = XGBClassifier(**kwargs_A)
    print("Training Variant A ... ", end="", flush=True)
    model_A.fit(X_train_A_bal, y_train_A_bal, eval_set=[(X_test_A_proc, y_test)], verbose=False)
    print("done.")

    joblib.dump(model_A, os.path.join(ARTEFACTS_DIR, "paysense_model_blended_training.pkl"))
    joblib.dump(prep_A, os.path.join(ARTEFACTS_DIR, "paysense_preprocessor_blended_training.pkl"))
    joblib.dump(FEATURE_NAMES_A, os.path.join(ARTEFACTS_DIR, "paysense_feature_names_blended_training.pkl"))
    print("Saved -> paysense_model_blended_training.pkl / paysense_preprocessor_blended_training.pkl")

    y_proba_A_test = model_A.predict_proba(X_test_A_proc)[:, 1]
    variant_A_test_metrics = metrics_from_scores(y_test.values, y_proba_A_test, DEPLOYED_THRESHOLD)
    variant_A_test_metrics["roc_auc_full"] = float(roc_auc_score(y_test, y_proba_A_test))
    print(f"Variant A canonical test @ tau={DEPLOYED_THRESHOLD}: "
          f"ROC-AUC={variant_A_test_metrics['roc_auc']:.4f} "
          f"recall={variant_A_test_metrics['recall']:.4f} "
          f"precision={variant_A_test_metrics['precision']:.4f}")
    results["variant_A_canonical_test"] = variant_A_test_metrics
    results["variant_A_canonical_test_sweep"] = sweep_thresholds(y_test, y_proba_A_test)

    # ════════════════════════════════════════════════════════════════════
    #  STEP 3 — Variant B: heavier regularization, ORIGINAL data only.
    #  Same preprocessor-fitting procedure as Block 0 (fit on X_train_raw
    #  only) -- functionally identical to the frozen preprocessor, only the
    #  model hyperparameters differ from baseline.
    # ════════════════════════════════════════════════════════════════════
    line("=")
    print("STEP 3 | Variant B -- heavier regularization, original data only")
    line("=")

    prep_B = build_preprocessor(CAT_COLS, NUM_COLS)
    prep_B.fit(X_train_raw)
    X_train_B_proc = prep_B.transform(X_train_raw)
    X_test_B_proc = prep_B.transform(X_test_raw)
    assert np.allclose(X_test_B_proc, X_test_frozen_proc), (
        "Variant B's rebuilt preprocessor disagrees with the frozen one on the test set."
    )

    X_train_B_bal, y_train_B_bal = smote.fit_resample(X_train_B_proc, y_train.values)

    kwargs_B = dict(BASE_XGB_KWARGS)
    kwargs_B.update(VARIANT_B_XGB_OVERRIDES)
    kwargs_B["monotone_constraints"] = monotone_tuple(FEATURE_NAMES)
    print(f"Variant B overrides vs. baseline: {VARIANT_B_XGB_OVERRIDES}")
    model_B = XGBClassifier(**kwargs_B)
    print("Training Variant B ... ", end="", flush=True)
    model_B.fit(X_train_B_bal, y_train_B_bal, eval_set=[(X_test_B_proc, y_test)], verbose=False)
    print("done.")

    joblib.dump(model_B, os.path.join(ARTEFACTS_DIR, "paysense_model_regularized.pkl"))
    print("Saved -> paysense_model_regularized.pkl (reuses the frozen preprocessor's fitting procedure)")

    y_proba_B_test = model_B.predict_proba(X_test_B_proc)[:, 1]
    variant_B_test_metrics = metrics_from_scores(y_test.values, y_proba_B_test, DEPLOYED_THRESHOLD)
    variant_B_test_metrics["roc_auc_full"] = float(roc_auc_score(y_test, y_proba_B_test))
    print(f"Variant B canonical test @ tau={DEPLOYED_THRESHOLD}: "
          f"ROC-AUC={variant_B_test_metrics['roc_auc']:.4f} "
          f"recall={variant_B_test_metrics['recall']:.4f} "
          f"precision={variant_B_test_metrics['precision']:.4f}")
    results["variant_B_canonical_test"] = variant_B_test_metrics
    results["variant_B_canonical_test_sweep"] = sweep_thresholds(y_test, y_proba_B_test)

    # ════════════════════════════════════════════════════════════════════
    #  STEP 4 — Ensemble-path evaluation (src.fraud_model.score()) on the
    #  held-out synthetic set (seed 918273) for A and B. Baseline's number
    #  is cited verbatim from SYNTHETIC_GROUNDING.md (already computed
    #  against this exact file) -- not re-run.
